"""
Mechanical translation of pyseobnr's waveform fits (IV_fits.py `InputValueFits`, MR_fits.py
`MergerRingdownFits`) to Julia: one `@inline` function per method, returning a NamedTuple keyed `h22, h21, ...`.
Expressions are emitted fully parenthesized (no reliance on operator precedence); numeric literals are the
shortest round-trip repr of the double Python parsed, so the Julia constants are bit-identical.

    python scripts/translate_pyseobnr_fits.py PYSEOBNR_SRC_DIR > src/GravitationalWaveforms/SEOBNRv5HM_fits.jl
"""

import ast
import os
import sys

FUNCS = {"abs": "abs", "exp": "exp", "sqrt": "sqrt", "log": "log", "sign": "sign"}


def expr(n):
    if isinstance(n, ast.Constant):
        if isinstance(n.value, bool) or not isinstance(n.value, (int, float)):
            raise ValueError(f"constant {n.value!r}")
        return repr(float(n.value)) if isinstance(n.value, float) else str(n.value)
    if isinstance(n, ast.Name):
        return n.id
    if isinstance(n, ast.Attribute):
        if isinstance(n.value, ast.Name) and n.value.id == "self":
            return n.attr
        raise ValueError(ast.dump(n))
    if isinstance(n, ast.UnaryOp):
        if isinstance(n.op, ast.USub):
            return f"(-{expr(n.operand)})"
        if isinstance(n.op, ast.UAdd):
            return expr(n.operand)
        raise ValueError(ast.dump(n))
    if isinstance(n, ast.BinOp):
        ops = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*", ast.Div: "/", ast.Pow: "^"}
        op = ops[type(n.op)]
        if op == "^" and isinstance(n.right, ast.Constant) and isinstance(n.right.value, int):
            return f"({expr(n.left)}^{n.right.value})"
        return f"({expr(n.left)} {op} {expr(n.right)})"
    if isinstance(n, ast.Call):
        f = n.func
        if isinstance(f, ast.Attribute) and isinstance(f.value, ast.Name) and f.value.id == "np" and f.attr in FUNCS:
            assert len(n.args) == 1 and not n.keywords
            return f"{FUNCS[f.attr]}({expr(n.args[0])})"
        if isinstance(f, ast.Name) and f.id in ("abs",):
            assert len(n.args) == 1 and not n.keywords
            return f"abs({expr(n.args[0])})"
        raise ValueError(ast.dump(n))
    if isinstance(n, ast.Subscript):
        if isinstance(n.slice, ast.Constant) and isinstance(n.slice.value, int):
            return f"{expr(n.value)}[{n.slice.value + 1}]"
        raise ValueError(ast.dump(n))
    if isinstance(n, ast.Tuple):
        return "(" + ", ".join(expr(e) for e in n.elts) + ("," if len(n.elts) == 1 else "") + ")"
    raise ValueError(ast.dump(n))


def method(fn, prefix):
    out, keys = [], []
    for st in fn.body:
        if isinstance(st, ast.Expr) and isinstance(st.value, ast.Constant):
            continue                                            # docstring
        if isinstance(st, ast.Assign) and len(st.targets) == 1:
            tg = st.targets[0]
            if isinstance(st.value, ast.Dict) and not st.value.keys:
                continue                                        # h_modes = {}
            if isinstance(tg, ast.Name):
                out.append(f"    {tg.id} = {expr(st.value)}")
                continue
            if isinstance(tg, ast.Subscript) and isinstance(tg.slice, ast.Tuple):
                l, m = (e.value for e in tg.slice.elts)
                k = f"h{l}{m}"
                if k in keys:
                    out.append(f"    {k} = {expr(st.value)}")
                else:
                    keys.append(k)
                    out.append(f"    {k} = {expr(st.value)}")
                continue
        if isinstance(st, ast.Return):
            continue
        raise ValueError(f"{fn.name}: {ast.dump(st)}")
    name = f"_{prefix}_{fn.name}"
    body = "\n".join(out)
    ret = ", ".join(f"{k} = {k}" for k in keys)
    return (f"@inline function {name}(v)\n"
            f"    nu, dm, chiS, chiAS, chi = v.nu, v.dm, v.chiS, v.chiAS, v.chi\n"
            f"    chi33, chi21A, chi44A, chi21D, chi44D = v.chi33, v.chi21A, v.chi44A, v.chi21D, v.chi44D\n"
            f"    nuprime, chi33abs, chi21Aabs, chi44Aabs = v.nuprime, v.chi33abs, v.chi21Aabs, v.chi44Aabs\n"
            f"{body}\n    return ({ret})\nend\n")


def translate(path, cls, prefix):
    tree = ast.parse(open(path).read())
    c = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == cls)
    res = []
    for fn in c.body:
        if isinstance(fn, ast.FunctionDef) and fn.name != "__init__":
            res.append(f"# pyseobnr 0.3.7 `{os.path.basename(path)}` `{cls}.{fn.name}`\n" + method(fn, prefix))
    return res


if __name__ == "__main__":
    src = sys.argv[1]
    print("# GENERATED by scripts/translate_pyseobnr_fits.py from pyseobnr 0.3.7 (eob/fits/IV_fits.py, MR_fits.py).")
    print("# Do not edit by hand: regenerate. Each function takes the fit variables of `_seobv5hm_fitvars` and")
    print("# returns one value per mode (h22, h33, h21, h44, h55, h32, h43; pyseobnr's dict keys).\n")
    for s in translate(os.path.join(src, "eob/fits/IV_fits.py"), "InputValueFits", "seobv5hm_iv"):
        print(s)
    for s in translate(os.path.join(src, "eob/fits/MR_fits.py"), "MergerRingdownFits", "seobv5hm_mr"):
        print(s)
