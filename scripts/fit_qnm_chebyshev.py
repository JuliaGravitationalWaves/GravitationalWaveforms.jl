"""
Chebyshev fits of the Kerr QNM frequencies pyseobnr 0.3.7 uses (`compute_QNM`: the `qnm` package's
interpolant, interp_only=True), for the SEOBNRv5HM merger-ringdown.

    python scripts/fit_qnm_chebyshev.py QNM_TABLE_CSV --emit > src/GravitationalWaveforms/SEOBNRv5HM_qnm.jl

The table comes from scripts/pyseobnr_hm_reference.py. Two pieces in |a|, [0, A_SPLIT] (NLO terms) and
[A_SPLIT, 0.9999] (NHI terms), each a Chebyshev series in y = sqrt(1 - |a|) mapped linearly onto [-1, 1] (the QNMs
go like sqrt(1 - a) near extremality). One series each for Re/Im omega, per (l, m) and per branch: m > 0 (a >= 0)
and the -m branch pyseobnr uses for a < 0 (evaluated at |a|). The upper piece is limited (~3e-5) by the
roughness of the `qnm` interpolant itself above a ~ 0.98, not by the series.
"""

import sys

import numpy as np
from numpy.polynomial import chebyshev as C

MODES = [(2, 2), (2, 1), (3, 3), (3, 2), (4, 4), (4, 3), (5, 5)]
A_SPLIT, A_MAX = 0.9, 0.9999
NLO, NHI = 16, 24


def _x(a, lo, hi):
    y, ylo, yhi = np.sqrt(1.0 - a), np.sqrt(1.0 - hi), np.sqrt(1.0 - lo)
    return 2.0 * (y - ylo) / (yhi - ylo) - 1.0


def main():
    path = sys.argv[1]
    d = np.loadtxt(path, delimiter=",", comments="#")
    out = []
    worst = [0.0, 0.0]
    for (l, m) in MODES:
        for mm in (m, -m):
            s = d[(d[:, 0] == l) & (d[:, 1] == mm)]
            a = s[:, 2]
            for piece, (lo, hi, n) in enumerate(((0.0, A_SPLIT, NLO), (A_SPLIT, A_MAX, NHI))):
                k = (a >= lo) & (a <= hi)
                x = _x(a[k], lo, hi)
                for col in (3, 4):
                    c = C.chebfit(x, s[k, col], n - 1)
                    e = np.max(np.abs(C.chebval(x, c) - s[k, col]) / np.abs(s[k, col]))
                    worst[piece] = max(worst[piece], e)
                    out.append(np.concatenate([c, np.zeros(max(NLO, NHI) - len(c))]))  # one length: runtime-indexable
    print(f"# max relative fit error, lower / upper piece: {worst[0]:.1e} / {worst[1]:.1e}", file=sys.stderr)
    if "--emit" not in sys.argv:
        return
    print("# GENERATED by scripts/fit_qnm_chebyshev.py from the `qnm` package interpolant pyseobnr 0.3.7 uses")
    print(f"# (`compute_QNM`, interp_only=True). Pieces |a| in [0, {A_SPLIT}] ({NLO} terms) and [{A_SPLIT}, {A_MAX}] ({NHI} terms),")
    print("# Chebyshev series in y = sqrt(1 - |a|) mapped linearly onto [-1, 1] over the piece. Max relative error vs the")
    print(f"# interpolant on its table: {worst[0]:.1e} (lower), {worst[1]:.1e} (upper; the interpolant itself is rough there).")
    print("# Order: (l, m) in (2,2), (2,1), (3,3), (3,2), (4,4), (4,3), (5,5); per mode the prograde branch (a >= 0) then")
    print("# the -m branch (a < 0, evaluated at |a|); per branch the lower then the upper piece; per piece Re omega then")
    print("# Im omega (M_f = 1, Im < 0). Lower-piece series are zero-padded to the common length.")
    print(f"const _SEOBV5HM_QNM_ASPLIT = {A_SPLIT!r}")
    print(f"const _SEOBV5HM_QNM_AMAX = {A_MAX!r}")
    print("const _SEOBV5HM_QNM_CHEB = (")
    for c in out:
        print("    (" + ", ".join(repr(float(v)) for v in c) + "),")
    print(")")


if __name__ == "__main__":
    main()
