"""
Translate pyseobnr 0.3.7's anti-symmetric-mode fits (eob/fits/asym_fits/fits_<lm>/<quantity>.npz, evaluated by
eob/fits/antisymmetric_modes.py::PredictorSparseFits) into explicit Julia polynomials.

    python scripts/translate_pyseobnr_asym_fits.py > src/GravitationalWaveforms/SEOBNRv5PHM_asym_fits_generated.jl

(run in the environment where pyseobnr is installed). A fit is `intercept + sum_j c_j / std_j (monomial_j(x) -
mean_j)` over the non-zero monomials in scikit-learn's PolynomialFeatures order; the generated function takes the
feature vector as separate arguments, in the order of `fits_iv_mrd_antisymmetric`.
"""

from pyseobnr.eob.fits.antisymmetric_modes import get_predictor_from_fits

# (ell, emm, quantity, dimension, feature names), as fits_iv_mrd_antisymmetric calls them
FITS = [
    (2, 2, "habs", 7, "nu, S_inplane, Sigma_inplane, chi_eff, chi_a, cos_2phiSigma, sin_2phiSigma"),
    (2, 2, "omega_peak", 7, "nu, S_inplane, Sigma_inplane, chi_eff, chi_a, cos_2phiSigma, sin_2phiSigma"),
    (2, 2, "omegalm", 7, "nu, S_inplane, Sigma_inplane, chi_eff, chi_a, cos_2phiSigma, sin_2phiSigma"),
    (2, 2, "c1f", 5, "nu, chi_eff, chi_a, cos_2phiS, sin_2phiS"),
    (2, 2, "c2f", 6, "nu, c1f_22, chi_eff, chi_a, cos_2phiS, sin_2phiS"),
    (3, 3, "omegalm", 7, "nu, S_inplane, Sigma_inplane, chi_eff, chi_a, cos_2phiSigma, sin_2phiSigma"),
    (4, 4, "omegalm", 7, "nu, S_inplane, Sigma_inplane, chi_eff, chi_a, cos_2phiSigma, sin_2phiSigma"),
]


def main():
    print("# GENERATED by scripts/translate_pyseobnr_asym_fits.py from pyseobnr 0.3.7 eob/fits/asym_fits; do not edit.")
    for ell, emm, qty, dim, names in FITS:
        p = get_predictor_from_fits(nb_dimensions=dim, ell=ell, emm=emm, quantity=qty)
        args = [a.strip() for a in names.split(",")]
        assert len(args) == dim
        print()
        print(f"# pyseobnr get_predictor_from_fits(nb_dimensions={dim}, ell={ell}, emm={emm}, quantity=\"{qty}\")")
        print(f"@inline function _seobv5phm_asymfit_{qty}_{ell}{emm}({', '.join(args)})")
        print(f"    acc = {float(p.intercept)!r}")
        for c, mu, mono in zip(p.scaled_nonzero_coefficients, p.nonzero_coefficients_mean, p.monomials):
            term = " * ".join(f"{args[v]}" if pw == 1 else f"{args[v]}^{pw}" for v, pw in sorted(mono.items()))
            print(f"    acc += {float(c)!r} * ({term} - {float(mu)!r})")
        print("    return acc")
        print("end")


if __name__ == "__main__":
    main()
