"""
Mechanical translation of pyseobnr's precessing post-Newtonian equations (`eob/dynamics/pn_evolution_opt.py`)
into Julia: `prec_eqns_20102022` (orbit-averaged precession of L_N-hat, S1, S2 and the orbital-frequency evolution,
the SEOBNRv5PHM "PN spin ODE") and `compute_Lvec_35PN_vec_opt` (the orbital angular momentum vector L from L_N-hat
and the spins), as `_seobv5phm_pn_rhs` and `_seobv5phm_Lvec`.

    python scripts/translate_pyseobnr_pn.py PYSEOBNR_SRC_DIR > src/GravitationalWaveforms/SEOBNRv5PHM_pn_generated.jl

Vectors (`Lh`, `S1`, `S2`, cross products, `vecL*`) become `SVector{3}`s; every arithmetic node is parenthesized
exactly as pyseobnr's AST groups it, integer literals become Float64, `**` with an integer exponent becomes `^`.
The pyseobnr RHS normalizes `Lh` in place (`Lh /= Lh_norm`, mutating the caller's state through numba); the port
normalizes a local copy. `compute_Lvec_35PN_vec_opt` is vectorized over samples in pyseobnr (`v` arrays, `.T`);
the port takes one sample.
"""

import ast
import os
import sys

NAMES = {"my_cross": "cross", "my_dot": "dot", "my_norm": "norm", "log": "log", "np.log": "log",
         "np.pi": "_PI", "np.euler_gamma": "_EULER_GAMMA"}


def expr(n):
    if isinstance(n, ast.Constant):
        if isinstance(n.value, bool) or not isinstance(n.value, (int, float)):
            raise ValueError(f"constant {n.value!r}")
        return repr(float(n.value))
    if isinstance(n, ast.Name):
        return n.id
    if isinstance(n, ast.Attribute):
        s = ast.unparse(n)
        if s in NAMES:
            return NAMES[s]
        if n.attr == "T":  # per-sample port: transposes are identities
            return expr(n.value)
        raise ValueError(s)
    if isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.USub):
        return f"(-{expr(n.operand)})"
    if isinstance(n, ast.BinOp):
        ops = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*", ast.Div: "/", ast.Pow: "^"}
        op = ops[type(n.op)]
        if op == "^" and isinstance(n.right, ast.Constant) and isinstance(n.right.value, int):
            return f"({expr(n.left)}^{n.right.value})"
        return f"({expr(n.left)} {op} {expr(n.right)})"
    if isinstance(n, ast.Call):
        f = ast.unparse(n.func)
        if f not in NAMES:
            raise ValueError(f"call {f}")
        return f"{NAMES[f]}({', '.join(expr(a) for a in n.args)})"
    raise ValueError(ast.dump(n))


def stmt(s):
    if isinstance(s, ast.Expr) and isinstance(s.value, ast.Constant):  # docstring
        return None
    if isinstance(s, ast.AugAssign):
        ops = {ast.Div: "/", ast.Mult: "*", ast.Add: "+", ast.Sub: "-"}
        t = s.target.id
        return f"{t} = ({t} {ops[type(s.op)]} {expr(s.value)})"
    if isinstance(s, ast.Assign):
        tg = s.targets[0]
        if isinstance(tg, ast.Tuple):
            return f"({', '.join(e.id for e in tg.elts)}) = ({', '.join(expr(e) for e in s.value.elts)})"
        return f"{tg.id} = {expr(s.value)}"
    raise ValueError(ast.dump(s))


def body(f, skip):
    out = []
    for s in f.body:
        if isinstance(s, ast.Return):
            continue
        if isinstance(s, ast.Assign) and isinstance(s.targets[0], ast.Name) and s.targets[0].id in skip:
            continue
        line = stmt(s)
        if line is not None:
            out.append("    " + line)
    return out


def main(src_dir):
    path = os.path.join(src_dir, "pyseobnr", "eob", "dynamics", "pn_evolution_opt.py")
    tree = ast.parse(open(path).read())
    fs = {f.name: f for f in tree.body if isinstance(f, ast.FunctionDef)}
    print("# GENERATED by scripts/translate_pyseobnr_pn.py from pyseobnr 0.3.7 eob/dynamics/pn_evolution_opt.py; do not edit.")
    print()
    print("const _PI = Float64(pi)")
    print("const _EULER_GAMMA = Float64(Base.MathConstants.eulergamma)")
    print()
    print('"""')
    print("    _seobv5phm_pn_rhs(z, nu, m_1, m_2, X1, X2) -> SVector{10}")
    print()
    print("pyseobnr `prec_eqns_20102022`: time derivatives of `z = (LNhat, S1, S2, omega)` (spins `S_i = chi_i m_i^2`,")
    print("total mass 1, time in units of M). `LNhat` is normalized before use.")
    print('"""')
    print("@inline function _seobv5phm_pn_rhs(z, nu, m_1, m_2, X1, X2)")
    print("    Lh = SVector(z[1], z[2], z[3])")
    print("    S1 = SVector(z[4], z[5], z[6])")
    print("    S2 = SVector(z[7], z[8], z[9])")
    print("    omega = z[10]")
    print("\n".join(body(fs["prec_eqns_20102022"], {"Lh", "S1", "S2", "omega", "derivs"})))
    print("    return SVector(LNhatdot_v10[1], LNhatdot_v10[2], LNhatdot_v10[3], S1dot_v9[1], S1dot_v9[2], S1dot_v9[3],")
    print("                   S2dot_v9[1], S2dot_v9[2], S2dot_v9[3], omega_dot)")
    print("end")
    print()
    print('"""')
    print("    _seobv5phm_Lvec(q, nu, X1, X2, v, S1, S2, Lh, S1sq, S2sq, S1S2, lNS1, lNS2) -> SVector{3}")
    print()
    print("pyseobnr `compute_Lvec_35PN_vec_opt` for one sample: the orbital angular momentum vector (4PN non-spinning,")
    print("3.5PN spin-orbit and spin-spin) from `LNhat`, the spins and `v = omega^(1/3)`.")
    print('"""')
    print("@inline function _seobv5phm_Lvec(q, nu, X1, X2, v, S1, S2, Lh, S1sq, S2sq, S1S2, lNS1, lNS2)")
    print("\n".join(body(fs["compute_Lvec_35PN_vec_opt"], set())))
    print("    return vecL")
    print("end")


if __name__ == "__main__":
    main(sys.argv[1])
