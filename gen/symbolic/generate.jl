# Generates src/GravitationalWaveforms/SEOBNRv5_ham_symbolic_generated.jl from the single Hamiltonian source
# `hamiltonians/v5phm.jl`: the SEOBNRv5PHM (`_seobv5phm_ham_call`) and aligned-spin SEOBNRv5 (`_seobv5_potentials`: the
# source with zero in-plane spins) Hamiltonian values and their derivatives, differentiated symbolically (memoised DAG
# derivative, symeob.jl) and emitted as straight-line CSE'd Julia.
#
#     julia +1.13.2 --project=gen/symbolic gen/symbolic/generate.jl          # write the file
#     julia +1.13.2 --project=gen/symbolic gen/symbolic/generate.jl check    # fail if the committed file differs

include(joinpath(@__DIR__, "symeob.jl"))

const ROOT = abspath(joinpath(@__DIR__, "..", ".."))
const SRC = joinpath(ROOT, "src", "GravitationalWaveforms")
const OUT = joinpath(SRC, "SEOBNRv5_ham_symbolic_generated.jl")
const HAM = joinpath(@__DIR__, "hamiltonians", "v5phm.jl")
parsefile(f) = Meta.parseall(read(f, String))
docstr(name, args, doc) = "\"\"\"\n    $name($(join(args, ", ")))\n\n$doc\n\"\"\"\n"

fh = find_function(parsefile(HAM), :seobnrv5phm_hamiltonian)

buf = IOBuffer()
println(buf, """
# GENERATED by gen/symbolic/generate.jl from gen/symbolic/hamiltonians/v5phm.jl; do not edit. Values and partial
# derivatives in (r, prst, pphi) at fixed spins and EOB parameters; every distinct subexpression is one local.
""")

# ---- SEOBNRv5PHM ----------------------------------------------------------------------------------------------------
# The value (pyseobnr `_call` layout) and derivatives in the pyseobnr method layouts (grad, hessian, dynamics, omega,
# auxderivs), plus one fused set per call pattern of the model; `_circ` quantities are at prst = 0, from the body
# re-run with prst fixed at 0 (simplified before differentiation). The prst = 0 functions keep the full argument list
# (prst unused) so the callers' argument splat stays the same. log / sqrt / non-integer powers are the NaN-outside-
# the-domain `_seobv5phm_n*` (the plunge's stop condition).
args, vars, env = symbolic_body(fh)
_, cvars, cenv = symbolic_body(fh; fixed = Dict{Symbol,Any}(:prst => 0))
Q = (vars[:r], vars[:prst], vars[:L])
H = env[:H]
gH = [dag_derivative(H, q) for q in Q]
hH = [dag_derivative(gH[i], Q[j]) for i in 1:3 for j in 1:3]   # row-major (r, prst, pphi)
dr(x) = dag_derivative(env[x], vars[:r])
aux = [dr(:A), dr(:Bnp), dr(:Bnpa), dr(:xi), dr(:Qq), dag_derivative(env[:Qq], vars[:prst]), dr(:Hodd), dr(:Bp), dr(:Heven)]
cr, cL = cvars[:r], cvars[:L]
cdHdr, om_c = dag_derivative(cenv[:H], cr), dag_derivative(cenv[:H], cL)
E(x) = env[x]

for (name, outs, doc) in (
        (:_seobv5phm_ham_call, collect(env[:__return]),
            "The SEOBNRv5PHM Hamiltonian and its potentials, pyseobnr `Ham_AvgS2precess_simple_cython_PA_AD._call` layout:\n" *
            "(H, xi, A, Bnp, Bnpa, Q, Heven, Hodd, Bp). `chi_1, chi_2` are the spin projections on LN_hat, `chi_L1, chi_L2`\n" *
            "on L_hat; `L` = p_phi."),
        (:_seobv5phm_ham_csi, [E(:xi)], "The tortoise factor xi (pyseobnr `csi`)."),
        (:_seobv5phm_sym_grad, gH, "(dH/dr, dH/dprst, dH/dpphi)."),
        (:_seobv5phm_sym_hessian, hH, "The 3x3 Hessian in (r, prst, pphi), row-major."),
        (:_seobv5phm_sym_dynamics, vcat(gH, [H, E(:xi)]), "(dH/dr, dH/dprst, dH/dpphi, H, xi)."),
        (:_seobv5phm_sym_omega, gH[3:3], "omega = dH/dpphi."),
        (:_seobv5phm_sym_auxderivs, aux, "(dA/dr, dBnp/dr, dBnpa/dr, dxi/dr, dQ/dr, dQ/dprst, dHodd/dr, dBp/dr, dHeven/dr)."),
        (:_seobv5phm_sym_rhs, vcat(gH, [H, E(:xi), om_c]),
            "(dH/dr, dH/dprst, dH/dpphi, H, xi, omega_circ = dH/dpphi at prst = 0): the equations of motion."),
        (:_seobv5phm_sym_tphi, [E(:xi), gH[2], gH[3]], "(xi, dH/dprst, dH/dpphi): the PA dt/dr, dphi/dr."),
        (:_seobv5phm_sym_state, [H, E(:Heven) + E(:Hodd), om_c], "(H, Heff, omega_circ): the mode amplitudes' inputs."),
        (:_seobv5phm_sym_pr_terms, [H, E(:xi), E(:A), E(:Bnp), E(:Heven), E(:Hodd), aux[6], gH[3], om_c],
            "(H, xi, A, Bnp, Heven, Hodd, dQ/dprst, omega, omega_circ): the PA `pr_eqn` inputs."),
        (:_seobv5phm_sym_pphi_terms, vcat([H, E(:xi), E(:A), E(:Bnp), E(:Bnpa), E(:Qq), E(:Heven), E(:Hodd), E(:Bp)], aux[1:8], [gH[3], om_c]),
            "(H, xi, A, Bnp, Bnpa, Q, Heven, Hodd, Bp, dA/dr, dBnp/dr, dBnpa/dr, dxi/dr, dQ/dr, dQ/dprst, dHodd/dr, dBp/dr,\n" *
            "omega, omega_circ): the PA `pphi_eqn` inputs."),
        (:_seobv5phm_sym_diss_terms, [H, E(:xi), gH[2], gH[3], om_c, hH[1], hH[3]],
            "(H, xi, dH/dprst, dH/dpphi, omega_circ, d2H/dr2, d2H/drdpphi): the dissipative IC residual."),
        (:_seobv5phm_sym_omega_circ, [om_c], "omega_circ = dH/dpphi at prst = 0 (prst unused)."),
        (:_seobv5phm_sym_j0, [cdHdr, dag_derivative(cdHdr, cL)],
            "(dH/dr, d2H/drdpphi) at prst = 0 (prst unused): the adiabatic j0 Newton step."),
        (:_seobv5phm_sym_circ_hessian, [cdHdr, om_c, dag_derivative(cdHdr, cr), dag_derivative(cdHdr, cL), dag_derivative(om_c, cL)],
            "(dH/dr, dH/dpphi, d2H/dr2, d2H/drdpphi, d2H/dpphi2) at prst = 0 (prst unused): the circular IC Newton step."))
    src, n = emit(outs, name, args; doc = docstr(name, args, doc))
    println(buf, src)
    println(stderr, "$name: $n locals")
end

# ---- aligned-spin call patterns -------------------------------------------------------------------------------------
# One fused function per call pattern of the aligned-spin models (fused value + derivative sets share their
# subexpressions), from one table: the models call `_seobv5_sym_rhs(r, prst, pphi, hp)` etc. with
# `hp::SEOBNRv5HamParams`, through the dispatch methods written after the set.
# Spins along L (in-plane components 0, chi_i = chi_Li = chiz_i), the spin combinations overridden with their aligned
# forms (those of `evaluate_H`): exact for spins along L, but the simplifier would not cancel e.g.
# nap2 = (ap2 - apz^2) / 2 with ap2 expanded, leaving the in-plane terms as round-off-sized dead weight. Typed `@Tlit T`
# code (Float32 works); sqrt guarded by max(x, floatmin) (no-op on the physical domain; finite inside the horizon, where
# the IMR plunge's trial RK stages can land).
#
# Each pattern: (name, circular (prst = 0, no prst argument), r-derivative order of its outputs, outputs, doc).
const PATTERNS = (
    (:potentials, false, 0, s -> [s.H, s.xi, s.A, s.Bnp, s.Bnpa, s.Q, s.Heven, s.Heff], ""),
    (:sym_gradient, false, 1, s -> [s.dHdr, s.dHdpr, s.omega], "(dH/dr, dH/dprst, dH/dpphi)."),
    (:sym_rhs, false, 1, s -> [s.H, s.xi, s.Heff, s.dHdr, s.dHdpr, s.omega, s.omega_circ],
        "(H, xi, Heff, dH/dr, dH/dprst, omega = dH/dpphi, omega_circ = dH/dpphi at prst = 0): the equations of motion."),
    (:sym_state, false, 0, s -> [s.H, s.Heff, s.omega_circ], "(H, Heff, omega_circ): the mode amplitudes' inputs."),
    (:sym_tphi, false, 0, s -> [s.xi, s.dHdpr, s.omega], "(xi, dH/dprst, dH/dpphi): the PA dt/dr, dphi/dr."),
    (:sym_auxderivs, false, 1, s -> s.aux, "pyseobnr `auxderivs`: (dA/dr, dBnp/dr, dBnpa/dr, dxi/dr, dQ/dr, dQ/dprst, dHodd/dr)."),
    (:sym_pr_terms, false, 0, s -> [s.H, s.xi, s.A, s.Bnp, s.Heven, s.Heff, s.aux[6], s.omega, s.omega_circ],
        "(H, xi, A, Bnp, Heven, Heff, dQ/dprst, omega, omega_circ): the PA `pr_eqn` inputs."),
    (:sym_pphi_terms, false, 1, s -> vcat([s.H, s.xi, s.A, s.Bnp, s.Bnpa, s.Q, s.Heven, s.Heff], s.aux, [s.omega, s.omega_circ]),
        "(H, xi, A, Bnp, Bnpa, Q, Heven, Heff, dA/dr, dBnp/dr, dBnpa/dr, dxi/dr, dQ/dr, dQ/dprst, dHodd/dr, omega,\n" *
        "omega_circ): the PA `pphi_eqn` inputs."),
    (:sym_diss_terms, false, 2, s -> [s.H, s.xi, s.Heff, s.dHdpr, s.omega, s.omega_circ, D(s.dHdr, s.r), D(s.dHdr, s.pphi)],
        "(H, xi, Heff, dH/dprst, omega, omega_circ, d2H/dr2, d2H/drdpphi): the dissipative IC residual."),
    (:sym_omega_circ, true, 0, s -> [s.omega_circ], "omega_circ = dH/dpphi at prst = 0."),
    (:sym_j0, true, 1, s -> [s.cdHdr, D(s.cdHdr, s.pphi)], "(dH/dr, d2H/drdpphi) at prst = 0: the adiabatic j0 Newton step."),
    (:sym_circ_hessian, true, 2, s -> [s.cdHdr, s.omega_circ, D(s.cdHdr, s.r), D(s.cdHdr, s.pphi), D(s.omega_circ, s.pphi)],
        "(dH/dr, dH/dpphi, d2H/dr2, d2H/drdpphi, d2H/dpphi2) at prst = 0: the circular IC Newton step."))

const D = dag_derivative

# the quantities the patterns read, from a family's environments at symbolic prst (`e`) and at prst = 0 (`ce`)
function pattern_inputs(e, ce, v; Q = :Qq)
    r, prst, pphi = v[:r], v[:prst], v[:pphi]
    # (this order of differentiation fixes the opaque-quotient numbering, hence the emitted code)
    H, cH = e[:H], ce[:H]
    dHdr, dHdpr, omega = D(H, r), D(H, prst), D(H, pphi)
    cdHdr, omega_circ = D(cH, r), D(cH, pphi)
    aux = [D(e[:A], r), D(e[:Bnp], r), D(e[:Bnpa], r), D(e[:xi], r), D(e[Q], r), D(e[Q], prst), D(e[:Hodd], r)]
    return (; r, prst, pphi, H, xi = e[:xi], A = e[:A], Bnp = e[:Bnp], Bnpa = e[:Bnpa], Q = e[Q], Heven = e[:Heven],
            Heff = e[:Heff], dHdr, dHdpr, omega, omega_circ, cdHdr, aux)
end

# a family's pattern set: `scalar(pat, circ, order)` -> (function name, scalar arguments); `wrapper(pat, circ, order)`
# -> the source of its dispatch method on the family's parameter type
function emit_patterns(io, s, scalar, wrapper, potdoc)
    for (pat, circ, order, outs, doc) in PATTERNS
        name, a = scalar(pat, circ, order)
        src, n = emit(outs(s), name, a; typed = true, logf = "log", sqrtf = "_seobv5_gsqrt", powf = "^",
                      doc = docstr(name, a, pat === :potentials ? potdoc : doc))
        println(io, src)
        println(stderr, "$name: $n locals")
    end
    println(io, "# dispatch on the parameter type (the models call these)")
    foreach(p -> println(io, wrapper(p[1], p[2], p[3])), PATTERNS)
    println(io)
end

v5name(pat) = pat === :potentials ? :_seobv5_potentials : Symbol(:_seobv5_, pat)
dargs(circ) = circ ? "r, pphi" : "r, prst, pphi"
noprst(a) = filter(!=(:prst), a)

# ---- SEOBNRv5 aligned spin ------------------------------------------------------------------------------------------
println(buf, "@inline _seobv5_gsqrt(x) = sqrt(max(x, floatmin(typeof(x))))\n")
const HP = (:nu, :X1, :X2, :chi1, :chi2, :a6, :dSO)               # SEOBNRv5HamParams fields
aargs = (:r, :prst, :pphi, HP...)
av = Dict(s => only(@variables $s) for s in aargs)
apv, amv = av[:X1] * av[:chi1] + av[:X2] * av[:chi2], av[:X1] * av[:chi1] - av[:X2] * av[:chi2]
function aligned_env(prst)
    _, _, e = symbolic_body(fh; override = Dict{Symbol,Any}(:ap2 => apv * apv, :am2 => amv * amv, :apam => amv * apv,
        :nap2 => 0, :nam2 => 0, :napnam => 0), fixed = Dict{Symbol,Any}(
        :r => av[:r], :prst => prst, :L => av[:pphi], :chix1 => 0, :chiy1 => 0, :chiz1 => av[:chi1], :chix2 => 0,
        :chiy2 => 0, :chiz2 => av[:chi2], :chi_1 => av[:chi1], :chi_2 => av[:chi2], :chi_L1 => av[:chi1],
        :chi_L2 => av[:chi2], :nu => av[:nu], :X_1 => av[:X1], :X_2 => av[:X2], :delta => av[:X1] - av[:X2],
        :a6 => av[:a6], :dSO => av[:dSO]))
    return e
end
emit_patterns(buf, pattern_inputs(aligned_env(av[:prst]), aligned_env(0), av),
    (pat, circ, _) -> (v5name(pat), circ ? noprst(aargs) : aargs),
    (pat, circ, _) -> "@inline $(v5name(pat))($(dargs(circ)), hp::SEOBNRv5HamParams) = $(v5name(pat))($(dargs(circ)), " *
                      join(("hp.$f" for f in HP), ", ") * ")",
    "The SEOBNRv5HM aligned-spin Hamiltonian (pyseobnr `Ham_align_a6_apm_AP15_DP23_gaugeL_Tay_C.evaluate_H`) and\n" *
    "its potentials: (H, xi, A, Bnp, Bnpa, Q, Heven, Heff), the tuple order of `_call` that the post-adiabatic\n" *
    "`pr_eqn` / `pphi_eqn` read. `pphi` = L; spins along L.")

for (file, code) in ((OUT, String(take!(buf))),)
    if get(ARGS, 1, "") == "check"
        if replace(read(file, String), "\r\n" => "\n") != code
            write(file * ".new", code)
            error("$file is stale (fresh output in $file.new): rerun gen/symbolic/generate.jl")
        end
        println("$file up to date")
    else
        write(file, code)
        println("wrote $file ($(count(==('\n'), code)) lines)")
    end
end
